    /**
     * @struct AuxVar
     * @brief Stores metadata for a generated auxiliary column to facilitate array padding.
     */
    struct AuxVar {
        std::string type;                                            ///< The C++ type (e.g. "double")
        std::string name;                                            ///< Unique name of the auxiliary variable
        std::string defaultVal;                                      ///< Default value for padding (usually NaN)
        std::unordered_map<std::string, std::string> detectorCols;   ///< Maps a detector name to its raw projection column
    };

    /**
     * @class ePICAssociationManager
     * @brief Manages the registration and building of PODIO associations.
     */
    class ePICAssociationManager {
    public:
        class ColumnBuilder; 

        /**
         * @brief Constructor.
         * @param reaction Reference to the base ePICReaction managing the dataframe.
         */
        explicit ePICAssociationManager(ePICReaction& reaction);

        /**
         * @brief Initiates the Fluent Builder for a specific detector.
         * @param detName The name of the registered detector (e.g., "Central", "RP").
         * @return A transient ColumnBuilder object to chain commands.
         */
        ColumnBuilder For(const std::string& detName);

        /**
         * @brief Compiles all registered associations into unified, padded RDataFrame columns.
         * @details Must be called after all `For()...As()` chains, but before `MakeCombinations()`.
         */
        void Build();
        
        /** @return Constant reference to the registered auxiliary variables. */
        const std::vector<AuxVar>& GetAuxVars() const;

        /** @return Reference to the underlying reaction object. */
        ePICReaction& GetReaction() const;

        /**
         * @brief Defines the base PODIO associations using generalized branch names.
         * @details Constructs the One-To-Many nested arrays using `rad::podio::CreateAssociation`.
         * @param uniqueId The custom variable name (e.g. "cal_energy") to prevent clashes.
         * @param relationName The exact EDM4hep relation name (e.g. "clusters", "tracks").
         * @param collectionNames Valid PODIO hit collections to merge.
         * @param memberName The leaf member to extract.
         * @param baseBranch The primary tracker branch (e.g. "ReconstructedParticles").
         */
        void DefineInternal(const std::string& uniqueId, const std::string& relationName, 
                            const ROOT::RVec<std::string>& collectionNames, 
                            const std::string& memberName, const std::string& baseBranch);
                            
        /**
         * @brief Projects a nested One-To-Many association array into a flat scalar array.
         * @param outName Base name of the output column.
         * @param inputAssociation Name of the nested column to project.
         * @param funcName The reducer function (e.g., "rad::util::First").
         * @param detName The mapped detector name.
         * @param type The underlying data type.
         * @param defaultVal Default value string for missing data.
         */
        void Project(const std::string& outName, const std::string& inputAssociation, const std::string& funcName,
                     const std::string& detName, const std::string& type = "double", std::string defaultVal = "");
                     
        /**
         * @brief Registers an auxiliary variable into the internal padding map.
         * @param type Data type.
         * @param name Name of the final column.
         * @param defaultVal Value used to pad indices that lack associated data.
         * @param detName Name of the specific detector.
         * @param rawCol The name of the raw unpadded RDataFrame column.
         */
        void RegisterAuxiliary(const std::string& type, const std::string& name, const std::string& defaultVal,
                               const std::string& detName, const std::string& rawCol);

    private:
        ePICReaction& _reaction;      ///< Reference to the parent reaction managing the RDF node
        std::vector<AuxVar> _auxVars; ///< Registry of requested auxiliary columns
    };

    /**
     * @class ePICAssociationManager::ColumnBuilder
     * @brief Transient helper class that implements the Fluent API for column definition.
     */
    class ePICAssociationManager::ColumnBuilder {
    public:
        /**
         * @brief Constructor.
         * @param manager Reference to the parent manager.
         * @param detName The detector being mapped.
         */
        ColumnBuilder(ePICAssociationManager& manager, const std::string& detName);

        /**
         * @brief Sets the PODIO collections to extract data from.
         * @param cols List of valid EDM4hep collections.
         * @return Reference to the builder for chaining.
         */
        ColumnBuilder& From(const ROOT::RVec<std::string>& cols);

        /**
         * @brief Sets the specific leaf variable to extract from the collection.
         * @param member Member name (e.g., "energy", "time").
         * @return Reference to the builder for chaining.
         */
        ColumnBuilder& Extract(const std::string& member);

        /**
         * @brief Sets the reducer function used to collapse One-To-Many relations into scalars.
         * @param reducer Function name (e.g., "rad::util::Sum"). Defaults to First.
         * @return Reference to the builder for chaining.
         */
        ColumnBuilder& Reduce(const std::string& reducer);
        
        /**
         * @brief Explicitly set the EDM4hep Relation branch to read from.
         * @param rel The relation name (Defaults to "clusters", but could be "tracks").
         * @return Reference to the builder for chaining.
         */
        ColumnBuilder& Relation(const std::string& rel);

        /**
         * @brief Terminal operation. Finalizes the configuration and triggers the definitions.
         * @param outName The final desired name of the column (without type prefix).
         * @param type The underlying data type (default "double").
         * @param defaultVal Default padding value. If empty, uses `rad::consts::InvalidEntry`.
         */
        void As(const std::string& outName, const std::string& type = "double", std::string defaultVal = "");

    private:
        ePICAssociationManager& _manager; ///< Parent manager execution hook
        std::string _detName;             ///< Target detector string
        ROOT::RVec<std::string> _collections; ///< Target PODIO collections
        std::string _memberName;          ///< Leaf member
        std::string _reducerFunc;         ///< Reducer function
        std::string _relationName;        ///< EDM4hep Relation name
    };

