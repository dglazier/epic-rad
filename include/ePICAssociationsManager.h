/**
 * @file ePICAssociationsManager.h
 * @brief Handles unpacking of PODIO One-To-Many relationships dynamically using a Fluent Builder API.
 * @details
 * This manager decouples the low-level detector hit/cluster association logic from the core physics kinematics 
 * inside `ePICReaction`. It uses a **Fluent Builder Pattern** (method chaining) to provide an intuitive interface 
 * for mapping nested PODIO arrays into flat, padded `RDataFrame` columns.
 * * The manager completely shields the user from complex JIT string manipulations and ensures the resulting 
 * arrays are perfectly synchronized with the unified `rec_det_id` track arrays generated by the `ParticleInjector`.
 * * **Fluent API Code Structure & Example:**
 * The `For()` method initializes a transient `ColumnBuilder` object. Methods like `From()`, `Extract()`, and 
 * `Relation()` return a reference to this builder, allowing them to be chained together sequentially. 
 * The `As()` method acts as the terminal operation, finalizing the configuration and registering the variable.
 * Finally, `Build()` constructs the unified padded arrays.
 * * \code
 * epic::ePICAssociationManager assoc(rad_df);
 * * // Define cluster energy extraction for the Central tracker
 * assoc.For("Central")
 * .Relation("clusters") // (Optional) defaults to "clusters"
 * .From({"EcalBarrelClusters", "EcalEndcapPClusters", "EcalEndcapNClusters"})
 * .Extract("energy")
 * .Reduce("rad::util::First") // (Optional) defaults to First
 * .As("cal_energy", "double"); // Automatically maps to padded "rec_cal_energy"
 * * // Execute JIT compilation to pad arrays using rec_det_id
 * assoc.Build(); 
 * \endcode
 */

