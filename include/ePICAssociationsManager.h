    inline ePICAssociationManager::ePICAssociationManager(ePICReaction& reaction) : _reaction(reaction) {}

    inline ePICAssociationManager::ColumnBuilder ePICAssociationManager::For(const std::string& detName) {
        return ColumnBuilder(*this, detName);
    }

    inline const std::vector<AuxVar>& ePICAssociationManager::GetAuxVars() const { return _auxVars; }
    inline ePICReaction& ePICAssociationManager::GetReaction() const { return _reaction; }

    inline void ePICAssociationManager::RegisterAuxiliary(const std::string& type, const std::string& name, const std::string& defaultVal,
                                                          const std::string& detName, const std::string& rawCol) 
    {
        for (auto& aux : _auxVars) {
            if (aux.name == name) {
                if (!rawCol.empty()) aux.detectorCols[detName] = rawCol;
                return;
            }
        }
        AuxVar newAux{type, name, defaultVal, {}};
        if (!rawCol.empty()) newAux.detectorCols[detName] = rawCol;
        _auxVars.push_back(newAux);
    }

    inline void ePICAssociationManager::DefineInternal(const std::string& uniqueId, 
                                                       const std::string& relationName,
                                                       const ROOT::RVec<std::string>& collectionNames, 
                                                       const std::string& memberName,
                                                       const std::string& baseBranch) 
    {
        if(!_reaction.GetMetadata()) throw std::runtime_error("ePICAssociationManager::DefineInternal requires PodioMetadata.");
        if (collectionNames.empty()) return;

        ROOT::RVec<std::string> validNames;
        ROOT::RVecU validIDs;
        for(const auto& name : collectionNames) {
            if(_reaction.GetMetadata()->Exists(name)) {
                validNames.push_back(name);
                validIDs.push_back(_reaction.GetMetadata()->CollectionIDFor(name));
            }
        }
        if(validNames.empty()){
            throw std::runtime_error("ePICAssociationManager::DefineInternal input data does not have branch");
        }

        std::string recType = rad::consts::data_type::Rec();
        std::string dnwTag = rad::DoNotWriteTag();

        // 1. Unified Index
        std::string unifiedIdxName = recType + uniqueId + "_unified_idx" + dnwTag;
        if(!_reaction.ColumnExists(unifiedIdxName)) {
            rad::podio::IdToLocalIndexMap mapper(validIDs);
            _reaction.Define(unifiedIdxName, [mapper](const ROOT::RVecU& ids){ return mapper(ids); }, 
                             {"_" + baseBranch + "_" + relationName + ".collectionID"});
        }

        // 2. Prepare Inputs
        ROOT::RVec<std::string> leafCols;
        for(const auto& name : validNames) leafCols.push_back(name + "." + memberName);

        std::string typeName = _reaction.GetElementTypeName(leafCols[0]); 
        
        std::string packName = recType + uniqueId + "_" + memberName + "_pack" + dnwTag;
        _reaction.Define(packName, "ROOT::RVec<ROOT::RVec<" + typeName + ">>{" + rad::util::combineVectorToString(leafCols) + "}");

        // 3. Define Final Output
        std::string outputCol = recType + uniqueId + "_assoc" + dnwTag; 
        
        std::string assocExpr = "rad::podio::CreateAssociation<" + typeName + ">(" + 
            packName + ", " + 
            unifiedIdxName + ", " + 
            "_" + baseBranch + "_" + relationName + ".index, " +
            baseBranch + "." + relationName + "_begin, " +
            baseBranch + "." + relationName + "_end)";
                                
        _reaction.Define(outputCol, assocExpr);
    }

    inline void ePICAssociationManager::Project(const std::string& outName, 
                                                const std::string& inputAssociation, 
                                                const std::string& funcName,
                                                const std::string& detName,
                                                const std::string& type,
                                                std::string defaultVal) 
    {
        if (defaultVal.empty()) {
            defaultVal = "rad::consts::InvalidEntry<" + type + ">()";
        }

        std::string recType = rad::consts::data_type::Rec();
        std::string dnwTag = rad::DoNotWriteTag();

        std::string rawCol = (!detName.empty()) ? (recType + outName + "_raw" + dnwTag) : outName;
        auto inputString = inputAssociation + dnwTag;
        
        std::string expr = "ROOT::RVec<" + type + "> result; result.reserve(" + inputString + ".size()); "
                           "for(const auto& v : " + inputString + ") { "
                           "result.push_back(static_cast<" + type + ">(" + funcName + "(v))); } "
                           "return result;";
                           
        _reaction.Define(rawCol, expr);

        if (!detName.empty()) {
            RegisterAuxiliary(type, outName, defaultVal, detName, rawCol);
        }
    }

