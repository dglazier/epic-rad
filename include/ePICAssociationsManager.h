    inline ePICAssociationManager::ColumnBuilder::ColumnBuilder(ePICAssociationManager& manager, const std::string& detName) 
        : _manager(manager), _detName(detName), _reducerFunc("rad::util::First"), _relationName("clusters") {} 

    inline ePICAssociationManager::ColumnBuilder& ePICAssociationManager::ColumnBuilder::From(const ROOT::RVec<std::string>& cols) {
        _collections = cols; return *this;
    }

    inline ePICAssociationManager::ColumnBuilder& ePICAssociationManager::ColumnBuilder::Extract(const std::string& member) {
        _memberName = member; return *this;
    }

    inline ePICAssociationManager::ColumnBuilder& ePICAssociationManager::ColumnBuilder::Reduce(const std::string& reducer) {
        _reducerFunc = reducer; return *this;
    }

    inline ePICAssociationManager::ColumnBuilder& ePICAssociationManager::ColumnBuilder::Relation(const std::string& rel) {
        _relationName = rel; return *this;
    }

    inline void ePICAssociationManager::ColumnBuilder::As(const std::string& outName, const std::string& type, std::string defaultVal) {
        if (defaultVal.empty()) {
            defaultVal = "rad::consts::InvalidEntry<" + type + ">()";
        }

        auto detDef = _manager.GetReaction().GetDetector(_detName);
        
        // Pass the unique name (outName) AND the PODIO relationship (_relationName)
        _manager.DefineInternal(outName, _relationName, _collections, _memberName, detDef.branch);
        
        std::string recType = rad::consts::data_type::Rec();
        
        // Project the newly created unique association column
        _manager.Project(outName, recType + outName + "_assoc", _reducerFunc, _detName, type, defaultVal);
    }

    inline void ePICAssociationManager::Build() {
        std::string recType = rad::consts::data_type::Rec();
        std::string detIdCol = recType + "det_id"; // Synced with ParticleInjector

        for (const auto& aux : _auxVars) {
            std::string finalCol = recType + aux.name; 
            
            std::string expr = "ROOT::RVec<" + aux.type + "> unified(" + detIdCol + ".size(), " + aux.defaultVal + "); ";
            
            // 1. Declare all local index trackers BEFORE the loop
            for (const auto& [detName, rawCol] : aux.detectorCols) {
                expr += "int local_idx_" + detName + " = 0; ";
            }
            
            // 2. Open the single loop
            expr += "for(size_t i = 0; i < " + detIdCol + ".size(); ++i) { ";
            
            // 3. Add an IF block for each detector inside the loop
            for (const auto& [detName, rawCol] : aux.detectorCols) {
                auto detDef = _reaction.GetDetector(detName);
                expr += "    if(" + detIdCol + "[i] == " + std::to_string(detDef.id) + ") { ";
                expr += "        if(local_idx_" + detName + " < " + rawCol + ".size()) { ";
                expr += "            unified[i] = " + rawCol + "[local_idx_" + detName + "]; ";
                expr += "        } ";
                expr += "        local_idx_" + detName + "++; ";
                expr += "    } ";
            }
            
            // 4. Close the loop and return
            expr += "} return unified;";

            _reaction.Define(finalCol, expr);
        }
    }
  
